

function highlight() {
    //Write your code here
	const sTag = document.querySelectorAll("strong");
	sTag.forEach((iteams),()=>{
		iteams.style.color = "rgb(0,128,0)";
	});
}


function return_normal() {
	sTag.forEach((iteams),()=>{
		const sTag = document.querySelectorAll("strong");
		iteams.style.color = "rgb(0,0,0)";
	});
}
